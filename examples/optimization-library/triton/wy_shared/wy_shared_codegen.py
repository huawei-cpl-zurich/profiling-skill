"""Auditable source extraction; generated bodies keep per-file Apache/FLA notices."""
from pathlib import Path
import difflib
import hashlib
import json
HERE=Path(__file__).resolve().parent


def generate():
    original=(HERE/'vendor/src/triton_ascend_kernels/attention/fla/wy_fast.py').read_text()
    start=original.index('@triton.jit');end=original.index('\n\ndef recompute_w_u_fwd(')
    body=original[start:end];old='b_w = tl.dot(b_A, b_kb)'
    if body.count(old)!=1:raise ValueError('exact W precision patch mismatch')
    common=body.replace(old,'b_w = tl.dot(b_A, b_kb, allow_tf32=False)')
    u=common.index('        for i_v in range(');w=common.index('        for i_k in range(')
    parts=dict(fused=common,w=common[:u]+common[w:],u=common[:w])
    text=original[:original.index('from typing')]+'''# Generated by wy_shared_codegen.py; do not edit.
import triton
import triton.language as tl

'''
    for name,source in parts.items():text+=source.replace('def recompute_w_u_fwd_kernel(',f'def wy_{name}_kernel(')+'\n\n'
    return text, ''.join(difflib.unified_diff(body.splitlines(True),common.splitlines(True),fromfile='source-kernel',tofile='common-ieee-kernel'))


if __name__=='__main__':
    text,patch=generate();(HERE/'wy_shared_generated.py').write_text(text);(HERE/'common-ieee.patch').write_text(patch)
