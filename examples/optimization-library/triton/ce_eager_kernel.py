@triton.jit
def ce_delayed_gradient(X_ptr, Y_ptr, M_ptr, D_ptr, n_cols, n_non_ignore,
                        label_smoothing: tl.constexpr, BLOCK_SIZE: tl.constexpr):
    program_id = tl.program_id(0).to(tl.int64)
    X_ptr += program_id * n_cols
    y = tl.load(Y_ptr + program_id).to(tl.int32)
    if y == -100:
        for i in range(0, n_cols, BLOCK_SIZE):
            offsets = i + tl.arange(0, BLOCK_SIZE)
            tl.store(X_ptr + offsets, 0.0, mask=offsets < n_cols)
        return
    m = tl.load(M_ptr + program_id)
    d = tl.load(D_ptr + program_id)
    lse = m + tl.log(d)
    eps = label_smoothing / n_cols
    HAS_SOFTCAPPING: tl.constexpr = False
    HAS_WEIGHT: tl.constexpr = False
    reduction: tl.constexpr = "mean"
    lse_square_scale: tl.constexpr = 0.0
    for i in range(0, n_cols, BLOCK_SIZE):
        X_offsets = i + tl.arange(0, BLOCK_SIZE)
        X_block = tl.load(
            X_ptr + X_offsets,
            mask=X_offsets < n_cols,
            other=float("-inf"),
            # Ensure float32 precision for softmax calculation
        ).cast(tl.float32)
        if HAS_SOFTCAPPING:
            intermediate = tanh(X_block / softcap)
            X_block = softcap * intermediate

        if not HAS_WEIGHT:
            # cal softmax(x_i)
            X_block = tl.exp(X_block - m) / d
            # derivative of z-loss: 2 * lse_square_scale * lse * softmax(x_i)
            X_block += 2 * lse_square_scale * lse * X_block
            # smoothing term
            X_block += -eps
            # special handle dx_y
            X_block = tl.where(X_offsets != y, X_block, X_block - (1 - label_smoothing))
            # reduction scale
            if reduction == "mean":
                X_block = X_block / n_non_ignore
        else:
            weight_block = tl.load(weight_ptr + X_offsets, mask=X_offsets < n_cols)
            softmax_X = tl.exp(X_block - m) / d
            # derivative of original_loss
            dloss_ori = (1 - label_smoothing) * softmax_X
            # specially handle dx_y
            dloss_ori = tl.where(
                X_offsets != y, dloss_ori, dloss_ori - (1 - label_smoothing)
            )
            dloss_ori = dloss_ori * weight_y
            # derivative of smooth_loss
            dloss_smooth = eps * (-weight_block + softmax_X * weight_sum)
            # derivative of z-loss
            dz_loss = 2 * lse_square_scale * lse * softmax_X
            # reduction scale
            if reduction == "mean":
                dloss_ori = dloss_ori / sum_non_ignore_weight
                dloss_smooth = dloss_smooth / sum_non_ignore_weight
                dz_loss = dz_loss / n_non_ignore
            # derivative of total_loss
            X_block = dloss_ori + dloss_smooth + dz_loss

        # chain rule softcapping
        # d(softcap * tanh(x / softcap)) = (1 - tanh^2(x / softcap))
        if HAS_SOFTCAPPING:
            X_block = X_block * (1 - intermediate * intermediate)

        tl.store(X_ptr + X_offsets, X_block, mask=X_offsets < n_cols)


@triton.jit
def ce_reset_copy(X, W, L, V: tl.constexpr, B: tl.constexpr):
    row = tl.program_id(0)
    tile = tl.program_id(1)
    col = tile * B + tl.arange(0, B)
    x = tl.load(X + row * V + col, col < V, other=0.0)
    tl.store(W + row * V + col, x, col < V)
    if tile == 0:
        tl.store(L + row, 0.0)

@triton.jit
def ce_loss_zero(L, ROWS: tl.constexpr):
    row = tl.program_id(0)
    tl.store(L + row, 0.0)
