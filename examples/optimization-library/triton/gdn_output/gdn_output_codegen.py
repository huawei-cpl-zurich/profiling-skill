"""Source-preserving three-producer ablation; original source remains in vendor/."""
from pathlib import Path
import hashlib,json
HERE=Path(__file__).resolve().parent


def generate():
    original=(HERE/'vendor/src/triton_ascend_kernels/attention/fla/chunk_o.py').read_text()
    body=original[original.index('@triton.jit'):original.index('\n\ndef chunk_fwd_o(')]
    def remove(text,start,end):
        a=text.index(start);b=text.index(end,a);return text[:a]+text[b:]
    state=body.replace('        b_A = tl.zeros([BT, BT], dtype=tl.float32)\n','')
    state=remove(state,'            p_k = tl.make_block_ptr(','            p_h = tl.make_block_ptr(')
    state=state.replace('            b_k = tl.load(p_k, boundary_check=(0, 1))\n','').replace('            b_A += tl.dot(b_q, b_k)\n','')
    state=state.replace('            b_A = b_A * safe_exp(b_g[:, None] - b_g[None, :])\n','')
    state=remove(state,'        o_i = tl.arange(','        p_o = tl.make_block_ptr(')
    state=remove(state,'        b_v = tl.load(','        tl.store(')
    state=state.replace('        tl.store(p_o,','        b_o = b_o * scale\n        tl.store(p_o,')
    local=body.replace('        b_o = tl.zeros([BT, BV], dtype=tl.float32)\n','')
    local=remove(local,'            p_h = tl.make_block_ptr(','            # [BT, BK]')
    local=local.replace('            b_h = tl.load(p_h, boundary_check=(0, 1))\n','').replace('            b_o += tl.dot(b_q, b_h)\n','').replace('            b_o = b_o * tl.exp(b_g)[:, None]\n','')
    local=local.replace('b_o = b_o * scale + tl.dot(b_A.to(b_v.dtype), b_v) * scale','b_o = tl.dot(b_A.to(b_v.dtype), b_v) * scale')
    text=original[:original.index('from typing')]+'''# Generated by gdn_output_codegen.py; do not edit.
import triton
import triton.language as tl
from gdn_output_helper import safe_exp

'''
    for name,source in [('fused',body),('state',state),('local',local)]:
        text+=source.replace('def chunk_fwd_kernel_o(',f'def gdn_output_{name}(')+'\n\n'
    text+='''@triton.jit
def gdn_output_combine(state, local, out, N:tl.constexpr, BLOCK:tl.constexpr):
    i=tl.program_id(0)*BLOCK+tl.arange(0,BLOCK)
    a=tl.load(state+i,i<N,other=0)
    b=tl.load(local+i,i<N,other=0)
    tl.store(out+i,a+b,i<N)
'''
    utils=(HERE/'vendor/src/triton_ascend_kernels/attention/fla/utils.py').read_text()
    helper=utils[:utils.index('import torch')]+ 'import triton\nimport triton.language as tl\n\n'+utils[utils.index('@triton.jit\ndef safe_exp'):]
    return text,helper


if __name__=='__main__':
    text,helper=generate();(HERE/'gdn_output_generated.py').write_text(text);(HERE/'gdn_output_helper.py').write_text(helper)
    (HERE/'vendor-manifest.json').write_text(json.dumps({str(p.relative_to(HERE)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((HERE/'vendor').rglob('*')) if p.is_file()},indent=2)+'\n')
